#** 기능개발 유의사항[2][처리 및 상태]
###########################################################################################################################################################
1) 메시지 접수 우선 순위
* MSG_PRIORITY 입력 시 우선 순위로 전송(기본 값 : 3) : MSG_PRIORITY 3:일반성 전송 / 7:긴급성 전송
- 메시지는 일반적으로  RES_DATE와 MSG_KEY를 기준으로 선입선출 방식으로 처리
- 마지막에 넣었지만 최우선 접수 요청시에는 MSG_PRIORITY를 7로 입력.
- MSG_TYPE 마다 각각 우선순위를

2) 메시지 상태값(결과 확인)
* MSG_STATE(메시지상태) =  1:입력(전송대기),  3:발송준비(QUE 수집), 5:결과대기(G/W접수 완료, 발송 결과 대기, SMS/RCS:24시간, MMS:72시간), 6:결과처리 완료(결과회신)

[*중요*] 성공 실패는 MSG_STATE 와 RSLT_CODE 값을 조합해서 분석이 필요

* 성공은 아래와 같습니다.
예) [성공]: MSG_STATE='6' AND RSLT_CODE IN ('0','1000')

* 실패는 아래와 같습니다.
예) [실패]: MSG_STATE='6' AND RSLT_CODE NOT IN ('0','1000') : 상태 코드 NURI2_NRMSG_RSLT 코드 조회

*아래는 MSG_STATE 상태 설명
[완료] : MSG_STATE='6' : 성공 또는 실패등 명확한 결과가 확인됨
[대기] : MSG_STATE='5' : 발송 결과 대기 상태, XMS(문자)로 처리된 경우 대기 시간이 SMS:24시간, MMS(LMS):72시간 대기시간이 필요함.
[큐잉] : MSG_STATE='3' : 메시지를 Queue에 적재
[입력] : MSG_STATE='1' : 메시지 입력 상태

[★][결과코드 분석 방법: 기타]
 - MSG_STATE='6' 성공, 실패등 결과가 확인 된 경우 RSLT_CODE로 분석
 - RSLT_CODE는 3자리코드, 1리 코드, 4자리 코드등이 있습니다
 - * 3자리 코드: 1XX, 2XX, 3XX, 4XX, 5XX, 9XX가 있습니다. 이 경우는 누리2 내부실패로 발송이되지 않은 상태
 - * 1자리 코드: 메시지 서버, 또는 이통사에서 회신된 결과 코드입니다.
 - * 4자리 코드: 메시지 서버, 카카오, RCS 결과코드
