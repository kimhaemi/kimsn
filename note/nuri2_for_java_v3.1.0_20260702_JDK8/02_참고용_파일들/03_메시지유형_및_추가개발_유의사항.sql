#** MSG_TYPE 전송 우선 순위 설정
###########################################################################################################################################################
* [중요] MSG_TYPE_1이 xMS(SMS/MMS) 일때는 다음 MSG_TYPE_2, MSG_TYPE_3을 처리 하지 않음
* [중요] 반드시 xMS(SMS/MMS)는 마지막 MSG_TYPE 으로 처리 해야 합니다.

--------------------------------------------------------------------------------
* 메시지 유형 설명.
--------------------------------------------------------------------------------
* ALT??  : 카카오 알림톡을 의미합니다.
* RCS??  : 공식명칭 Rich Communication Services 또는 안심문자, 문자 기능개선 서비스로 메시지 읽음처리, 발신자 정보명확성
* xMS란??:  SMS(Short Message Service), MMS(Multimedia Message Service), LMS(Long Message Service)
 공통명칭 앞자리를 'x'로 변경하여 공통서비스 명칭인 xMS(XMS)로 칭함

- MSG_TYPE_1,MSG_TYPE_2, MSG_TYPE_3 :최대 3번 전송시도 가능 -- [대분류] : SMS:단문 메시지, MMS:멀티메시지(장문, 첨부), ALT:카카오 알림톡 메시지, RCS: 안심문자
- CONTENTS_TYPE_1, CONTENTS_TYPE_2, CONTENTS_TYPE_3 :       -- [소분류] : SMS:단문 메시지, LMS:장문, MMS:멀티메시지(장문+첨부, 첨부), ALT:카카오 알림톡 메시지, RCS: 안심문자
--------------------------------------------------------------------------------

-- ALT(알림톡, 카카오) 처리 1~2순위 권장.
* [중요][ALT](알림톡) 처리 :  MSG_TYPE_1~2='ALT', CONTENTS_TYPE_1~2='ALT'

-- RCS 처리 1~2순위 권장.
* [중요][RCS-SMS][RCS] 처리 :  MSG_TYPE_1~2='RCS', CONTENTS_TYPE_1~2='RCS'
* [중요][RCS-LMS][RCL] 처리 :  MSG_TYPE_1~2='RCS', CONTENTS_TYPE_1~2='RCL'
* [중요][RCS-MMS][RCM] 처리 :  MSG_TYPE_1~2='RCS', CONTENTS_TYPE_1~2='RCM'

-- xMS 처리, ALT/RCS 사용시  2~3순위 권장
* [중요][SMS] 처리 :  MSG_TYPE_1~3='SMS', CONTENTS_TYPE_1~3='SMS' : SMS, SMS
* [중요][LMS] 처리 :  MSG_TYPE_1~3='MMS', CONTENTS_TYPE_1~3='LMS' : MMS, LMS
* [중요][MMS] 처리 :  MSG_TYPE_1~3='MMS', CONTENTS_TYPE_1~3='MMS' : MMS, MMS


