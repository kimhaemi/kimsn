NRMSG_RSLT(NURI2_NRMSG_RSLT) : 전송 결과 코드정보 테이블, 해당 테이블에 RSLT_CODE 를 조회 하여 RSLT_EXPLA 참고, 값 수정 가능
------------------------------------------
2.[필수][추가] : NRMSG_DATA(NURI2_NRMSG_DATA), 월단위, 연단위, 설정에 따른 테이블 자동생성
NRMSG_LOG(NRMSG_LOG_YYYYMM) : MSG_STATE='6'(상태완료)인 메시지를 저장하는 테이블(NRMSG_DATA 와 컬럼(필드)이 같음), (NURI2_)NRMSG_DATA 에서는 삭제 (NURI2_)NRMSG_LOG(_YYYYMM) 로 이동됨.
 - 실시간, 배치(5) 모드가 있음
 - 로그(NRMSG_LOG) 테이블은 MSG_STATE=6 인 데이터가 있을 때 생성 됩니다. 모듈 기동시 없을 수 있습니다.
------------------------------------------
3.[선택][추가]: 이중화 설정시 자동생성.
NRMSG_DUPLEX(NURI2_NRMSG_DUPLEX) : 이중화를 위한 테이블(nuri2.conf 설정한 경우 생성, duplex_switch = ON)(*절대 수정불가)
